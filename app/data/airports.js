// "JFK" → "JFK — New York"
export function displayName(code) {
  const a = airports[String(code || "").toUpperCase()];
  if (!a) return String(code || "");
  return `${code.toUpperCase()} — ${a.city}`;
}

// Flat list for the combobox dropdown, sorted by city then code.
export const airportList = Object.entries(airports)
  .map(([code, d]) => ({
    code,
    city: d.city,
    country: d.country,
    name: d.name,
    label: `${code} — ${d.city}`,
    search: `${code} ${d.city} ${d.name}`.toLowerCase(),
  }))
  .sort((a, b) => a.label.localeCompare(b.label));
